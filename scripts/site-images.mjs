// Builds content-hashed, right-sized renditions of the home hero slides and the category tiles, and writes the manifest
// config/data/siteImages.ts. Hashed names let next.config.ts cache them for a year.
// Sources live in assets/site-images/ (hero-N.webp, hero-N-m.webp, categories/<slug>.webp). Run: node scripts/site-images.mjs
import fs from 'fs';
import path from 'path';
import crypto from 'crypto';
import sharp from 'sharp';

const ROOT = process.cwd();
const SRC = path.join(ROOT, 'assets', 'site-images');
const OUT = path.join(ROOT, 'public', 'images');
const hashOf = (buf) => crypto.createHash('md5').update(buf).digest('hex').slice(0, 8);

async function emit(input, dir, base, width, quality, suffix = '', avif = false) {
  const pipe = sharp(input).resize({ width, withoutEnlargement: true });
  const buf = await (avif ? pipe.avif({ quality, effort: 5 }) : pipe.webp({ quality, effort: 6 })).toBuffer();
  const name = `${base}.${hashOf(buf)}${suffix}.${avif ? 'avif' : 'webp'}`;
  fs.mkdirSync(path.join(OUT, dir), { recursive: true });
  fs.writeFileSync(path.join(OUT, dir, name), buf);
  return `/images/${dir}/${name}`;
}

// clear previously generated renditions
for (const dir of ['home', 'categories']) {
  const d = path.join(OUT, dir);
  if (fs.existsSync(d)) for (const f of fs.readdirSync(d)) if (/\.[0-9a-f]{8}(-\d+)?\.(webp|avif)$/.test(f)) fs.unlinkSync(path.join(d, f));
}

const hero = [];
for (let n = 1; n <= 5; n++) {
  const d = await emit(path.join(SRC, `hero-${n}.webp`), 'home', `hero-${n}`, 1600, 66);
  const m = await emit(path.join(SRC, `hero-${n}-m.webp`), 'home', `hero-${n}-m`, 760, 64);
  const dAvif = await emit(path.join(SRC, `hero-${n}.webp`), 'home', `hero-${n}`, 1600, 42, '', true);
  const mAvif = await emit(path.join(SRC, `hero-${n}-m.webp`), 'home', `hero-${n}-m`, 760, 40, '', true);
  hero.push({ d, m, dAvif, mAvif });
}

const categories = {};
for (const f of fs.readdirSync(path.join(SRC, 'categories'))) {
  if (!f.endsWith('.webp')) continue;
  const slug = f.replace('.webp', '');
  const input = path.join(SRC, 'categories', f);
  const small = await emit(input, 'categories', slug, 480, 68, '-480');
  const large = await emit(input, 'categories', slug, 960, 68, '-960');
  categories[`/images/categories/${slug}.webp`] = { src: large, srcSet: `${small} 480w, ${large} 960w` };
}

const ts = `// Generated by scripts/site-images.mjs. Do not edit by hand.\nexport const HERO_IMAGES: { d: string; m: string; dAvif: string; mAvif: string }[] = ${JSON.stringify(hero, null, 2)};\n\nexport const CATEGORY_IMAGES: Record<string, { src: string; srcSet: string }> = ${JSON.stringify(categories, null, 2)};\n`;
fs.writeFileSync(path.join(ROOT, 'config', 'data', 'siteImages.ts'), ts);
console.log('hero', hero.length, 'categories', Object.keys(categories).length);
